export function getHadithOfTheDay() {
  const today = new Date();
  const startOfYear = new Date(today.getFullYear(), 0, 0);
  const diff = today - startOfYear;
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const dailyIndex = dayOfYear % HADITHS.length;
  return HADITHS[dailyIndex];
}

export function getRandomHadith(excludeId = null) {
  const filtered = excludeId !== null ? HADITHS.filter(h => h.id !== excludeId) : HADITHS;
  const randomIndex = Math.floor(Math.random() * filtered.length);
  return filtered[randomIndex];
}
